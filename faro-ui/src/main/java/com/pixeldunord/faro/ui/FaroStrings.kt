        /** The built-in texts for a language tag (`es`, `pt-BR`, `en-GB`…); English if unknown. */
        public fun forLocale(locale: String?): FaroStrings =
            when (locale.orEmpty().lowercase().replace('_', '-').substringBefore('-')) {
                "es" -> Spanish
                "pt" -> Portuguese
                else -> English
            }

        internal fun supports(locale: String?): Boolean =
            locale.orEmpty().lowercase().replace('_', '-').substringBefore('-') in setOf("en", "es", "pt")
    }
