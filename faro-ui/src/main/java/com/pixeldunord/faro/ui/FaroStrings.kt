        FaroKind.PROBLEM -> kindProblem
        FaroKind.SUGGESTION -> kindSuggestion
        FaroKind.QUESTION -> kindQuestion
    }

    /** One line saying what [kind] is for. */
    public fun kindHint(kind: FaroKind): String = when (kind) {
        FaroKind.PROBLEM -> kindProblemHint
        FaroKind.SUGGESTION -> kindSuggestionHint
        FaroKind.QUESTION -> kindQuestionHint
    }

